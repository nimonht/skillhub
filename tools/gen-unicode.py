#!/usr/bin/env python3
"""Generate src/core/sh_unicode_tables.h: the few Unicode properties the C core needs to behave like Qt's QChar in 1.x.

usage: python3 tools/gen-unicode.py > src/core/sh_unicode_tables.h

- space: QChar::isSpace (tab to carriage return, space, U+0085, and the separator categories Zs, Zl, Zp)
- letter or number: QChar::isLetterOrNumber (categories L* and N*)
- lowercase: the simple lowercase mapping (one code point to one code point), used for slugs and case-insensitive sorting
"""
import sys
import unicodedata

MAX = 0x110000


def ranges(pred):
    out, start = [], None
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            hit = False
        else:
            hit = pred(chr(cp))
        if hit and start is None:
            start = cp
        elif not hit and start is not None:
            out.append((start, cp - 1))
            start = None
    if start is not None:
        out.append((start, MAX - 1))
    return out


def is_space(ch):
    cp = ord(ch)
    return cp == 0x20 or 0x09 <= cp <= 0x0D or cp == 0x85 or unicodedata.category(ch) in ("Zs", "Zl", "Zp")


def is_alnum(ch):
    return unicodedata.category(ch)[0] in ("L", "N")


def lower_pairs():
    out = []
    for cp in range(MAX):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        low = chr(cp).lower()
        if len(low) == 1 and ord(low) != cp:
            out.append((cp, ord(low)))
    out.append((0x130, 0x69))  # U+0130 lowercases to "i" plus a combining dot; its simple mapping is plain i
    return sorted(set(out))


def emit(name, rows, per_line=6):
    print("static const uint32_t %s[][2] = {" % name)
    for i in range(0, len(rows), per_line):
        print("    " + " ".join("{0x%X, 0x%X}," % r for r in rows[i:i + per_line]))
    print("};")
    print()


print("// Generated by tools/gen-unicode.py from Unicode %s (Python %s). Do not edit." %
      (unicodedata.unidata_version, sys.version.split()[0]))
print("// Sorted ranges and pairs; looked up by binary search in sh_utf.c.")
print("#pragma once")
print()
print("#include <stdint.h>")
print()
emit("sh_uni_space_table", ranges(is_space))
emit("sh_uni_alnum_table", ranges(is_alnum))
emit("sh_uni_lower_table", lower_pairs())
